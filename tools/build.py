def sfx_dir():
    """Sound effects bundled with the HyperFrames CLI (free, see CREDITS.md there)."""
    for root in (subprocess.run(["npm", "root", "-g"], capture_output=True, text=True).stdout.strip(), str(ROOT / "node_modules")):
        p = Path(root) / "hyperframes/dist/skills/media-use/audio/assets/sfx"
        if root and p.exists():
            return p
    return None


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    vdir = (ROOT / sys.argv[1]).resolve() if not Path(sys.argv[1]).is_absolute() else Path(sys.argv[1])
    layout, channel, video, words = load(vdir)
    out = vdir / "build"
    (out / "compositions").mkdir(parents=True, exist_ok=True)
    media, small = prepare_media(vdir, video, out)
    world = build_world(vdir, layout, channel, video, media)
    overlays = build_overlays(layout, channel, video, media)
    captions, ncap = build_captions(layout, channel, video, words)
    write(out / "compositions/world.html", world)
    write(out / "compositions/overlays.html", overlays)
    write(out / "compositions/captions.html", captions)
    mix = vdir / "audio/mix.wav"
    if mix.exists():
        (out / "assets").mkdir(parents=True, exist_ok=True)
        if not (out / "assets/mix.wav").exists() or not filecmp.cmp(mix, out / "assets/mix.wav", shallow=False):
            shutil.copy(mix, out / "assets/mix.wav")
    write(out / "index.html", build_index(video, mix.exists()))
    (vdir / "qa").mkdir(exist_ok=True)
    write(vdir / "qa/harness.html", build_qa(world, overlays, captions))
    write(out / "hyperframes.json", json.dumps({"$schema": "https://hyperframes.heygen.com/schema/hyperframes.json", "paths": {"blocks": "compositions", "assets": "assets"}, "media": {"autoProxy": True}}, indent=2))
    write(out / "meta.json", json.dumps({"id": video["slug"], "name": video["slug"]}, indent=2))
    write(out / "package.json", json.dumps({"name": video["slug"], "private": True, "type": "module", "scripts": {
        "check": f"npx --yes hyperframes@{HF_VERSION} check", "render": f"npx --yes hyperframes@{HF_VERSION} render"}}, indent=2))
    missing = sorted({s[1] for s in video.get("sfx", [])} - {p.name for p in (sfx_dir() or Path("/nonexistent")).glob("*.mp3")})
    print(json.dumps({"build": str(out.relative_to(ROOT) if out.is_relative_to(ROOT) else out), "duration": video["duration"], "caption_groups": ncap,
                      "overlays": len(video.get("overlays", [])), "sfx": len(video.get("sfx", [])), "sfx_missing": missing,
                      "audio_in_preview": mix.exists(), "photos": len(media), "photos_small": small}))


if __name__ == "__main__":
    main()
