# ---------------------------------------------------------------- captions
def caption_groups(words, fix, max_chars, max_words):
    toks = []
    for s, e, w in words:
        w = fix.get(w, w)
        if w.startswith("%") and toks:
            toks[-1][2] += w; toks[-1][1] = e; continue
        toks.append([s, e, w])
    groups, cur = [], []
    for tk in toks:
        if cur:
            text_len = len(" ".join(x[2] for x in cur + [tk]))
            if len(cur) >= max_words or text_len > max_chars or tk[0] - cur[-1][1] > 0.3 or cur[-1][2][-1] in ".?!:":
                groups.append(cur); cur = []
        cur.append(tk)
    if cur:
        groups.append(cur)
    return groups


